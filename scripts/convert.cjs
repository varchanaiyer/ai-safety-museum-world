#!/usr/bin/env node
/* Converts the museum's character grid and room modules into WorkAdventure
   maps, dressed as an exhibition: floors and wall faces tinted per hall, a
   kiosk for every exhibit with its title on the wall and the artifact under
   glass, a pool of light where the visitor stands, shadows along the walls,
   thresholds and plaques at hall doors, benches, plants, painted visitors,
   the Old Office behind glass, the gift shop, and the museum's name across
   the title wall. One map for the historic core, one per wing. */
"use strict";
const fs = require("fs"), path = require("path");
const load = require("./exhibits-index.cjs");
const { SIZE } = require("./paint.cjs");
const ROOT = path.join(__dirname, "..");
const M = load(ROOT);
const TS = require("./tileset.cjs")(M);
const S = 3, PX = S * SIZE;
function readEnv(k) { try { const m = fs.readFileSync(path.join(ROOT, ".env"), "utf8").match(new RegExp("^" + k + "=(.*)$", "m")); return m && m[1].trim(); } catch (e) { return null; } }
const BASE = (process.env.PLACARDS_BASE || readEnv("PLACARDS_BASE") || "https://world.aisafety.museum").replace(/\/$/, "");
const DIRS = [[0, 1], [0, -1], [1, 0], [-1, 0]];
const hash = s => { let h = 2166136261; for (const c of String(s)) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; };

const G = M.composed.MAP, GW = M.composed.MW, GH = M.composed.MH;
const cell = (x, y) => (x >= 0 && y >= 0 && x < GW && y < GH) ? G[y][x] : "#";
const isFloor = (x, y) => cell(x, y) === ".";
const rects = M.composed.ROOMRECTS;
function regionAt(x, y) {
  const ex = M.exhibits[cell(x, y)];
  if (ex && ex.wing !== "core" && rects.some(r => r.key === ex.wing)) return ex.wing;   /* an exhibit belongs to the room that declared it, even on a shared wall */
  for (const r of rects) if (x >= r.x0 && x <= r.x1 && y >= r.y0 && y <= r.y1) return r.key;
  return "core";
}
const regions = { core: { key: "core", name: "The Historic Core", bounds: { x0: 0, y0: 0, x1: M.coreW - 1, y1: M.coreH - 1 }, file: "core.tmj" } };
for (const r of rects) regions[r.key] = { key: r.key, name: M.ZONES[r.key].name, bounds: { x0: r.x0, y0: r.y0, x1: r.x1, y1: r.y1 }, file: r.key + ".tmj", def: M.rooms.find(d => d.key === r.key) };
const links = [], seenPair = new Set();
for (let y = 0; y < GH; y++) for (let x = 0; x < GW; x++) {
  if (!isFloor(x, y)) continue; const ra = regionAt(x, y);
  for (const [dx, dy] of [[1, 0], [0, 1]]) { const nx = x + dx, ny = y + dy; if (!isFloor(nx, ny)) continue; const rb = regionAt(nx, ny); if (ra === rb) continue; const key = [ra, rb].sort().join("|"); if (seenPair.has(key)) continue; seenPair.add(key); links.push({ a: { x, y, region: ra }, b: { x: nx, y: ny, region: rb } }); }
}
function facing(x, y) {
  for (const [dx, dy] of DIRS) if (isFloor(x + dx, y + dy)) return { dx, dy, fx: x + dx, fy: y + dy };
  for (const [dx, dy] of DIRS) if (cell(x + dx, y + dy) === "*" && isFloor(x + 2 * dx, y + 2 * dy)) return { dx, dy, fx: x + 2 * dx, fy: y + 2 * dy, glass: true };
  return null;
}
const gid = id => id + 1;
function prop(name, value) { const type = typeof value === "boolean" ? "bool" : typeof value === "number" ? (Number.isInteger(value) ? "int" : "float") : "string"; return { name, type, value }; }
function tileset() {
  return { columns: TS.cols, firstgid: 1, image: TS.file, imageheight: TS.height, imagewidth: TS.width, margin: 0, name: "museum", spacing: 0, tilecount: TS.tileCount, tileheight: SIZE, tilewidth: SIZE,
    tiles: [{ id: TS.T.COLLIDE, properties: [prop("collides", true)] }], properties: [prop("tilesetCopyright", "CC0. Generated by scripts/tileset.cjs for the Museum of AI Safety.")] };
}
